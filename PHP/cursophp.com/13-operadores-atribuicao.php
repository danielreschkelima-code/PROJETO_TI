<?php
// Operadores de atribuição

$a = 10;

// Atribuição com Adição
$a += 5; // É a mesma coisa que: $a = $a + 5;
echo $a;
echo "<hr>";

// Atribuição com Subtração
$a -= 5; // É a mesma coisa que: $a = $a - 5;
echo $a;
echo "<hr>";

// Atribuição com Multiplicação
$a *= 5; // É a mesma coisa que: $a = $a * 5;
echo $a;
echo "<hr>";

// Atribuição com Divisão
$a /= 5; // É a mesma coisa que: $a = $a / 5;
echo $a;
echo "<hr>";

// Atribuição com Módulo (Resto da divisão)
$a %= 5; // É a mesma coisa que: $a = $a % 5;
echo $a;